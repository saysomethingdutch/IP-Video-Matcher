"""Collect share-page metadata in visible Chrome, then stream signed OBS objects.

The site API is never called by this program.  Metadata is captured only from
the response generated by a visible Chrome share page.  Signed URLs are not
written to the manifest or logs.
"""
from __future__ import annotations

import argparse
import csv
from datetime import datetime, timezone
import fcntl
from functools import lru_cache
import hashlib
import http.client
import json
from pathlib import Path
import re
import shutil
import time
from urllib.parse import parse_qs, urlparse, urlsplit

from openpyxl import load_workbook
from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parents[2]
BOOK = Path('/Volumes/Element/ip-video-matcher-field-test/field-test/【G组】吞噬星空视频比对.xlsx')
TARGET = Path('/Volumes/Element/ip-video-matcher-field-test/evidence')
STATE = ROOT / 'workspace/tsxk/ezcun'
SHARE = 'https://www.ezcun.com/web/#/share?evidenceId='
API = '/web/api/evid/getEvidencePreviewById'
MIN_GAP = 5.5
MIN_FREE = 20 * 1024**3
CHECK_MODE = False
FIELDS = ['row', 'sheet_row', 'evidenceId', 'file_size_bytes', 'duration_ms',
          'startWitnessTime', 'finishedWitnessTime', 'url_expires_at', 'status', 'error']


class Challenge(RuntimeError):
    pass


class BrowserLost(RuntimeError):
    pass


class DirectUnsupported(RuntimeError):
    """The signed object URL does not permit an ordinary download."""


def safe_error(exc):
    first_line = str(exc).splitlines()[0] if str(exc) else type(exc).__name__
    return re.sub(r'https?://\S+', '[URL redacted]', first_line)[:200]


@lru_cache(maxsize=1)
def entries():
    book = load_workbook(BOOK, read_only=True, data_only=True)
    sheet = book['沈瑞曦']
    found = []
    # Deliberately touch only source columns; colleague conclusions are not read.
    for excel_row, cells in enumerate(sheet.iter_rows(min_row=402, max_row=801,
                                                    min_col=2, max_col=14,
                                                    values_only=True), 402):
        number = cells[0]  # B
        share_url = cells[11]  # M
        certificate_url = cells[12]  # N
        fragment = urlparse(str(share_url)).fragment
        evid = parse_qs(fragment.partition('?')[2]).get('evidenceId', [''])[0]
        if not evid or int(number) != 7813 + excel_row - 402:
            raise ValueError(f'Invalid input row {excel_row}: {number}, evidenceId present={bool(evid)}')
        found.append({'row': int(number), 'sheet_row': excel_row, 'evidenceId': evid,
                      'input_title': cells[1] or '',  # C
                      'input_url': cells[3] or '',  # E
                      'certificate_url': certificate_url or ''})
    book.close()
    if len(found) != 400 or len({e['evidenceId'] for e in found}) != 400:
        raise ValueError('Expected exactly 400 distinct evidence IDs')
    return found


@lru_cache(maxsize=1)
def check_entries():
    """Read only the seven input fields in the frozen CSV, never workbook conclusions."""
    path = ROOT / 'cases/tsxk_check30.csv'
    found = []
    with path.open(newline='', encoding='utf-8-sig') as handle:
        for row in csv.DictReader(handle):
            share_url = row['取证视频链接']
            evid = parse_qs(urlparse(share_url).fragment.partition('?')[2]).get('evidenceId', [''])[0]
            number = int(row['序号'])
            if not evid:
                raise ValueError(f'No evidenceId for check row {number}')
            found.append({'row': number, 'sheet_row': '', 'evidenceId': evid,
                          'input_title': row.get('标题', ''),
                          'input_url': f"https://www.bilibili.com/video/{row['BV']}"})
    if (len(found) != 30 or len({item['row'] for item in found}) != 30
            or len({item['evidenceId'] for item in found}) != 30):
        raise ValueError('Expected 30 distinct check rows')
    return found


def safe_write_json(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_suffix(path.suffix + '.tmp')
    temp.write_text(json.dumps(data, ensure_ascii=False, indent=2))
    temp.replace(path)


def manifest_path():
    return STATE / ('manifest_check30.csv' if CHECK_MODE else 'manifest.csv')


def write_manifest(rows):
    STATE.mkdir(parents=True, exist_ok=True)
    temp = manifest_path().with_suffix('.csv.tmp')
    with temp.open('w', newline='') as handle:
        writer = csv.DictWriter(handle, fieldnames=FIELDS)
        writer.writeheader()
        for row in rows:
            writer.writerow({key: row.get(key, '') for key in FIELDS})
    temp.replace(manifest_path())


def expiry_from_signed_url(url):
    query = {k.lower(): v[0] for k, v in parse_qs(urlparse(url).query).items()}
    date = query.get('x-obs-date') or query.get('x-amz-date')
    lifetime = query.get('x-obs-expires') or query.get('x-amz-expires')
    if date and lifetime:
        from datetime import timedelta
        start = datetime.strptime(date, '%Y%m%dT%H%M%SZ').replace(tzinfo=timezone.utc)
        return (start + timedelta(seconds=int(lifetime))).isoformat()
    for key in ('expires', 'expire'):
        if key in query:
            try:
                return datetime.fromtimestamp(int(query[key]), timezone.utc).isoformat()
            except ValueError:
                pass
    return ''


class Browser:
    def __init__(self, last_share_visit=0.0):
        self.playwright = sync_playwright().start()
        self.context = self.playwright.chromium.launch_persistent_context(
            str(STATE / 'chrome-profile'), channel='chrome', headless=False,
            accept_downloads=True, downloads_path=str(STATE / 'chrome-downloads'))
        self.page = self.context.pages[0] if self.context.pages else self.context.new_page()
        self.last_share_visit = last_share_visit

    def close(self):
        try:
            self.context.close()
        except Exception:
            pass
        try:
            self.playwright.stop()
        except Exception:
            pass

    def share_data(self, evidence_id):
        try:
            if self.page.is_closed():
                self.page = self.context.new_page()
        except Exception as exc:
            raise BrowserLost(safe_error(exc)) from exc
        wait = MIN_GAP - (time.monotonic() - self.last_share_visit)
        if wait > 0:
            time.sleep(wait)
        responses = []
        def capture(response):
            if API in response.url:
                responses.append(response)
        self.page.on('response', capture)
        self.last_share_visit = time.monotonic()
        try:
            self.page.goto(SHARE + evidence_id, wait_until='domcontentloaded', timeout=60000)
            deadline = time.monotonic() + 45
            while not responses and time.monotonic() < deadline:
                self.page.wait_for_timeout(250)
                self._check_challenge()
            self._check_challenge()
            if not responses:
                raise Challenge('Share page generated no preview response; stopping for inspection')
            response = responses[-1]
            if response.status == 418:
                raise Challenge('CloudWAF 418; stopping')
            if response.status != 200:
                raise RuntimeError(f'Preview HTTP {response.status}')
            payload = response.json()
            if not isinstance(payload, dict) or not isinstance(payload.get('data'), dict):
                raise RuntimeError('Unexpected preview JSON')
            items = payload['data'].get('caseSonEvidenceList') or []
            if len(items) != 1 or not items[0].get('fileUrl'):
                raise RuntimeError(f'Expected one video URL, got {len(items)} items')
            item = items[0]
            son = item.get('sonEvid') or {}
            return {
                'file_url': item['fileUrl'],
                'file_size_bytes': int(item.get('fileSize') or son.get('fileSize')),
                'duration_ms': int(son.get('duration') or 0),
                'startWitnessTime': son.get('startWitnessTime') or '',
                'finishedWitnessTime': son.get('finishedWitnessTime') or '',
                'originalMd5': son.get('originalMd5') or '',
                'encryptedMd5': son.get('encryptedMd5') or '',
                'url_expires_at': expiry_from_signed_url(item['fileUrl']),
            }
        except Exception as exc:
            if 'Target page, context or browser has been closed' in str(exc):
                raise BrowserLost(safe_error(exc)) from exc
            raise
        finally:
            try:
                self.page.remove_listener('response', capture)
            except Exception:
                pass

    def _check_challenge(self):
        body = self.page.locator('body').inner_text(timeout=10000)[:8000]
        if any(word in body.lower() for word in ('验证码', '人机验证', '访问被拦截',
                                               '安全验证', 'captcha', 'verify you are human')):
            raise Challenge('Verification or block page detected; stopping')
        if any(any(word in (frame.url or '').lower() for word in ('captcha', 'verify', 'challenge'))
               for frame in self.page.frames[1:]):
            raise Challenge('Verification frame detected; stopping')

    def download(self, signed_url, destination, expected_size):
        if shutil.disk_usage(TARGET.parent).free - expected_size < MIN_FREE:
            raise RuntimeError('External disk would fall below 20 GiB; stopping')
        if shutil.disk_usage(STATE).free - expected_size < 5 * 1024**3:
            raise RuntimeError('Internal Chrome download cache would fall below 5 GiB; stopping')
        destination.parent.mkdir(parents=True, exist_ok=True)
        partial = destination.with_suffix('.mp4.part')
        if partial.exists():
            partial.unlink()  # Retain completed files; incomplete browser downloads restart this row.
        try:
            download_page = self.context.new_page()
        except Exception as exc:
            raise BrowserLost(safe_error(exc)) from exc
        try:
            with download_page.expect_download(timeout=60000) as event:
                try:
                    download_page.goto(signed_url, wait_until='commit', timeout=60000)
                except Exception as exc:
                    if not any(marker in str(exc) for marker in ('ERR_ABORTED', 'Download is starting')):
                        raise
            download = event.value
            download.save_as(partial)
            if download.failure():
                raise RuntimeError(f'Browser download failed: {download.failure()}')
            download.delete()  # Chrome downloaded into its local cache before copying out.
        except Exception as exc:
            if 'Target page, context or browser has been closed' in str(exc):
                raise BrowserLost(safe_error(exc)) from exc
            raise
        finally:
            try:
                if not download_page.is_closed():
                    download_page.close()
            except Exception:
                pass
        actual_size = partial.stat().st_size
        if actual_size != expected_size:
            raise RuntimeError(f'Download size {actual_size} != expected {expected_size}')
        md5 = hashlib.md5()
        with partial.open('rb') as handle:
            for block in iter(lambda: handle.read(8 * 1024 * 1024), b''):
                md5.update(block)
        return partial, md5.hexdigest()


def digest_file(path):
    md5 = hashlib.md5()
    with path.open('rb') as handle:
        for block in iter(lambda: handle.read(8 * 1024 * 1024), b''):
            md5.update(block)
    return md5.hexdigest()


def matched_digest(digest, metadata):
    return [name for name in ('originalMd5', 'encryptedMd5')
            if metadata.get(name) and digest.lower() == metadata[name].lower()]


def download_http(signed_url, destination, expected_size):
    """Stream the page-provided OBS URL to a resumable part with only Range added."""
    destination.parent.mkdir(parents=True, exist_ok=True)
    partial = destination.with_suffix('.mp4.part')
    current = partial.stat().st_size if partial.exists() else 0
    if current > expected_size:
        partial.unlink()
        current = 0
    remaining = expected_size - current
    if shutil.disk_usage(destination.parent).free - remaining < MIN_FREE:
        raise RuntimeError('External disk would fall below 20 GiB; stopping')
    if remaining == 0:
        return partial, digest_file(partial)
    parsed = urlsplit(signed_url)
    if parsed.scheme != 'https' or not parsed.hostname:
        raise DirectUnsupported('Signed object URL is not HTTPS')
    target = parsed.path + (('?' + parsed.query) if parsed.query else '')
    connection = http.client.HTTPSConnection(parsed.hostname, parsed.port, timeout=60)
    try:
        connection.putrequest('GET', target, skip_accept_encoding=True)
        connection.putheader('Range', f'bytes={current}-')
        connection.endheaders()
        response = connection.getresponse()
        if response.status not in (200, 206):
            raise DirectUnsupported(f'Ordinary signed-URL download returned HTTP {response.status}')
        if response.status == 206:
            content_range = response.getheader('Content-Range') or ''
            if not content_range.startswith(f'bytes {current}-'):
                raise RuntimeError(f'Unexpected Content-Range start for offset {current}')
            mode = 'ab'
        else:
            mode = 'wb'  # Server ignored Range; restart from zero safely.
            current = 0
            if shutil.disk_usage(destination.parent).free - expected_size < MIN_FREE:
                raise RuntimeError('External disk would fall below 20 GiB; stopping')
        with partial.open(mode) as handle:
            while True:
                block = response.read(4 * 1024 * 1024)
                if not block:
                    break
                if shutil.disk_usage(destination.parent).free - len(block) < MIN_FREE:
                    raise RuntimeError('External disk would fall below 20 GiB; stopping')
                handle.write(block)
        if partial.stat().st_size != expected_size:
            raise RuntimeError(f'Partial download {partial.stat().st_size} != {expected_size}')
        return partial, digest_file(partial)
    finally:
        connection.close()


def run():
    global CHECK_MODE, TARGET
    parser = argparse.ArgumentParser()
    parser.add_argument('--check30', action='store_true')
    parser.add_argument('--rows', help='Comma-separated row numbers to download after metadata is complete')
    args = parser.parse_args()
    CHECK_MODE = args.check30
    TARGET = Path('/Volumes/Element/ip-video-matcher-field-test/evidence_check30' if CHECK_MODE
                  else '/Volumes/Element/ip-video-matcher-field-test/evidence')
    items = check_entries() if CHECK_MODE else entries()
    requested = {int(value) for value in args.rows.split(',')} if args.rows else None
    if requested is not None and not requested <= {item['row'] for item in items}:
        parser.error('Some requested rows are absent from the selected dataset')
    metadata_dir = STATE / ('metadata_check30' if CHECK_MODE else 'metadata')
    STATE.mkdir(parents=True, exist_ok=True)
    lock = (STATE / 'run.lock').open('w')
    try:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except BlockingIOError:
        lock.close()
        print('STOPPED_ALREADY_RUNNING: another evidence fetch holds the shared lock', flush=True)
        return 7
    records = {}
    if manifest_path().exists():
        with manifest_path().open(newline='') as handle:
            records = {int(r['row']): r for r in csv.DictReader(handle)}
    browser = Browser()
    restarts = 0

    def recover_browser():
        nonlocal browser, restarts
        restarts += 1
        if restarts > 8:
            raise BrowserLost('Chrome closed repeatedly; stopping after 8 restarts')
        last_visit = browser.last_share_visit
        browser.close()
        time.sleep(2)
        browser = Browser(last_share_visit=last_visit)
        print(f'BROWSER_RESTART count={restarts}', flush=True)

    def fresh_metadata(evidence_id):
        for attempt in (1, 2):
            try:
                return browser.share_data(evidence_id)
            except BrowserLost:
                if attempt == 2:
                    raise
                recover_browser()
        raise AssertionError('unreachable')

    try:
        for index, item in enumerate(items, 1):
            number = item['row']
            if records.get(number, {}).get('status') == 'ok':
                continue
            record = {k: item[k] for k in ('row', 'sheet_row', 'evidenceId')}
            try:
                meta = fresh_metadata(item['evidenceId'])
                record.update({k: meta[k] for k in FIELDS if k in meta})
                record['status'] = 'ok'
                safe_write_json(metadata_dir / f'{number}.json',
                                {k: v for k, v in meta.items() if k != 'file_url'})
            except Challenge:
                raise
            except BrowserLost:
                raise
            except Exception as exc:
                record.update(status='error', error=safe_error(exc))
            records[number] = record
            write_manifest([records[n] for n in sorted(records)])
            print(f'METADATA {index}/{len(items)} row={number} status={record["status"]}', flush=True)
        for attempt in (2, 3):
            missing = [item for item in items if records.get(item['row'], {}).get('status') != 'ok']
            if not missing:
                break
            for item in missing:
                number = item['row']
                record = {k: item[k] for k in ('row', 'sheet_row', 'evidenceId')}
                try:
                    meta = fresh_metadata(item['evidenceId'])
                    record.update({k: meta[k] for k in FIELDS if k in meta})
                    record['status'] = 'ok'
                    safe_write_json(metadata_dir / f'{number}.json',
                                    {k: v for k, v in meta.items() if k != 'file_url'})
                except Challenge:
                    raise
                except BrowserLost:
                    raise
                except Exception as exc:
                    record.update(status='error', error=safe_error(exc))
                records[number] = record
                write_manifest([records[n] for n in sorted(records)])
                print(f'METADATA_RETRY attempt={attempt} row={number} status={record["status"]}', flush=True)
        good = [records[n] for n in sorted(records) if records[n]['status'] == 'ok']
        total = sum(int(r['file_size_bytes']) for r in good)
        print(f'MANIFEST rows={len(records)} good={len(good)} bytes={total} gib={total/1024**3:.2f}', flush=True)
        if len(good) != len(items):
            print('METADATA_INCOMPLETE: downloads held until all entries succeed', flush=True)
            return 2
        results_path = STATE / ('downloads_check30.csv' if CHECK_MODE else 'downloads.csv')
        download_rows = {}
        if results_path.exists():
            with results_path.open(newline='') as handle:
                download_rows = {int(r['row']): r for r in csv.DictReader(handle)}
        def save_results():
            tmp = results_path.with_suffix('.tmp')
            with tmp.open('w', newline='') as handle:
                fields = ['row', 'status', 'bytes', 'md5', 'matched_md5', 'error']
                writer = csv.DictWriter(handle, fieldnames=fields)
                writer.writeheader()
                writer.writerows({k: row.get(k, '') for k in fields} for row in download_rows.values())
            tmp.replace(results_path)
        for index, item in enumerate(items, 1):
            number = item['row']
            if requested is not None and number not in requested:
                continue
            destination = TARGET / f'{number}.mp4'
            cached_meta_path = metadata_dir / f'{number}.json'
            cached_meta = json.loads(cached_meta_path.read_text()) if cached_meta_path.exists() else {}
            expected = int(records[number]['file_size_bytes'])
            if destination.is_file() and destination.stat().st_size == expected:
                existing_digest = digest_file(destination)
                matches = matched_digest(existing_digest, cached_meta)
                if matches:
                    download_rows[number] = {'row': number, 'status': 'ok', 'bytes': expected,
                                             'md5': existing_digest, 'matched_md5': '+'.join(matches)}
                    save_results()
                    print(f'VERIFIED_EXISTING row={number} bytes={expected} md5={"+".join(matches)}', flush=True)
                    continue
                print(f'EXISTING_UNVERIFIED row={number}; redownloading', flush=True)
            try:
                for trial in (1, 2, 3):
                    try:
                        meta = fresh_metadata(item['evidenceId'])
                        size = int(meta['file_size_bytes'])
                        try:
                            partial, digest = download_http(meta['file_url'], destination, size)
                        except DirectUnsupported:
                            if trial < 3:
                                print(f'DIRECT_UNSUPPORTED_RETRY row={number}', flush=True)
                                continue  # A fresh share URL distinguishes expiry from rejection.
                            print(f'BROWSER_FALLBACK row={number}', flush=True)
                            partial, digest = browser.download(meta['file_url'], destination, size)
                        matched = matched_digest(digest, meta)
                        if not matched:
                            partial.unlink(missing_ok=True)
                            raise RuntimeError('Downloaded MD5 matches neither original nor encrypted MD5')
                        partial.replace(destination)
                        row = {'row': number, 'status': 'ok', 'bytes': size,
                               'md5': digest, 'matched_md5': '+'.join(matched)}
                        break
                    except BrowserLost:
                        if trial == 3:
                            raise
                        recover_browser()
                    except Challenge:
                        raise
                    except Exception:
                        if trial == 3:
                            raise
                        print(f'DOWNLOAD_RETRY row={number}', flush=True)
            except Challenge:
                raise
            except BrowserLost:
                raise
            except Exception as exc:
                row = {'row': number, 'status': 'error', 'error': safe_error(exc)}
                download_rows[number] = row
                save_results()
                print(f'DOWNLOAD {index}/{len(items)} row={number} error={row["error"]}', flush=True)
                if requested is not None or '20 GiB' in row['error']:
                    return 3
                continue
            download_rows[number] = row
            save_results()
            print(f'DOWNLOAD {index}/{len(items)} row={number} ok bytes={size} md5={row["matched_md5"]}', flush=True)
        scoped = requested if requested is not None else {item['row'] for item in items}
        ok = [download_rows[n] for n in scoped if download_rows.get(n, {}).get('status') == 'ok']
        print(f'COMPLETE downloaded={len(ok)} bytes={sum(int(r["bytes"]) for r in ok)} '
              f'failed={len(scoped)-len(ok)}', flush=True)
        return 0 if len(ok) == len(scoped) else 4
    except Challenge as exc:
        print(f'STOPPED_CHALLENGE {exc}', flush=True)
        return 5
    except BrowserLost as exc:
        print(f'STOPPED_BROWSER {safe_error(exc)}', flush=True)
        return 6
    finally:
        browser.close()
        fcntl.flock(lock, fcntl.LOCK_UN)
        lock.close()


if __name__ == '__main__':
    raise SystemExit(run())
